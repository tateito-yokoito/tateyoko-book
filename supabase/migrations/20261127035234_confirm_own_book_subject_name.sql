-- Confirm the subject's structured name before a self BOOK purchase. The
-- account, linked family-tree person, and generated draft title change in one
-- transaction. Gift and proxy projects cannot use this function.
create function public.confirm_own_book_subject_name(
  input_project_id uuid, input_family_name text, input_given_name text
) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  actor uuid := (select auth.uid());
  project public.book_projects%rowtype;
  subject public.persons%rowtype;
  account public.profiles%rowtype;
  new_family text := btrim(coalesce(input_family_name, ''));
  new_given text := btrim(coalesce(input_given_name, ''));
  full_name text;
begin
  if actor is null then
    raise exception 'Authentication is required' using errcode='42501';
  end if;
  if new_family = '' or new_given = '' or length(new_family) > 80
    or length(new_given) > 80 or new_family ~ '[[:cntrl:]]'
    or new_given ~ '[[:cntrl:]]' then
    raise exception '姓と名を入力してください' using errcode='22023';
  end if;
  full_name := new_family || ' ' || new_given;

  select * into project from public.book_projects
    where id=input_project_id and owner_user_id=actor and status='active'
    for update;
  if project.id is null or project.subject_person_id is null
    or not exists (
      select 1 from public.user_person_links link
      where link.user_id=actor and link.person_id=project.subject_person_id
        and link.role='self'
    ) then
    raise exception 'BOOKとご本人の対応を確認できません' using errcode='42501';
  end if;

  select * into subject from public.persons
    where id=project.subject_person_id and family_id=project.family_id for update;
  select * into account from public.profiles where id=actor for update;
  if subject.id is null or account.id is null then
    raise exception 'ご本人のプロフィールを確認できません' using errcode='42501';
  end if;

  if account.family_name is distinct from new_family
    or account.given_name is distinct from new_given
    or account.display_name is distinct from full_name then
    insert into public.profile_name_change_logs (
      user_id, previous_family_name, previous_given_name, previous_display_name,
      new_family_name, new_given_name, new_display_name
    ) values (
      actor, account.family_name, account.given_name, account.display_name,
      new_family, new_given, full_name
    );
  end if;

  update public.profiles set family_name=new_family, given_name=new_given,
    name=full_name, display_name=full_name, preferred_name=new_given || 'さん'
    where id=actor;
  update public.persons set family_name=new_family, given_name=new_given,
    display_name=full_name, preferred_name=new_given || 'さん'
    where id=subject.id;
  -- Only rename an untouched autogenerated draft title. Published snapshots
  -- and custom titles must stay as they are.
  if project.access_status not in ('paid','gifted','legacy')
    and project.title = subject.display_name || 'さんの縦糸横糸' then
    update public.book_projects set title=full_name || 'さんの縦糸横糸'
      where id=project.id;
  end if;

  return jsonb_build_object('person_id',subject.id,'display_name',full_name,
    'family_name',new_family,'given_name',new_given);
end;
$$;
revoke all on function public.confirm_own_book_subject_name(uuid,text,text) from public,anon;
grant execute on function public.confirm_own_book_subject_name(uuid,text,text) to authenticated;
